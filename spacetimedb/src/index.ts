// A reducer to log a new incident (simulating a zero-day or telemetry anomaly)

export const logIncident = db.reducer(
  { 
    logId: t.string(), 
    componentId: t.string(), 
    description: t.string(), 
    severity: t.string() 
  },
  (ctx, { logId, componentId, description, severity }) => {
    // Insert into table using snake_case column names
    ctx.db.incident_log.insert({ 
      log_id: logId, 
      component_id: componentId, 
      description, 
      severity, 
      timestamp: Date.now() 
    });

    // Automatically trigger work order cascade on critical severity
    if (severity === "Critical") {
      const orderId = `WO-${logId}`;
      ctx.db.work_order.insert({
        order_id: orderId,
        component_id: componentId,
        description: `Auto-dispatch: Cascade mitigation required for ${componentId}`,
        status: "Pending",
        priority: "Urgent",
      });
    }
  }
);

