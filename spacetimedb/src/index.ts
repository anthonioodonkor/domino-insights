import { schema, table, t } from 'spacetimedb/server';

const db = schema({
  // 1. The Physical Buildings
  facility: table({ public: true }, {
    facility_id: t.string().primaryKey(),
    name: t.string(),
    location: t.string(),
    overall_status: t.string(), // e.g., 'Normal', 'Warning', 'Critical'
  }),

  // 2. The Fragmented Systems inside the building
  system_component: table({ public: true }, {
    component_id: t.string().primaryKey(),
    facility_id: t.string(),
    system_type: t.string(), // e.g., 'HVAC', 'Access Control', 'Telemetry Node'
    dependency_id: t.string(), // What this system relies on (creates the "Invisible Network")
    status: t.string(),
  }),

  // 3. Telemetry/Security Logs for the LLM to analyze
  incident_log: table({ public: true }, {
    log_id: t.string().primaryKey(),
    component_id: t.string(),
    description: t.string(), // e.g., 'Unmonitored telemetry anomaly in cooling loop'
    severity: t.string(),
    timestamp: t.number(),
  }),

  // 4. Dependencies between infrastructure components (e.g., Chiller -> CRAH -> Server Hall)
  system_dependency: table({ public: true }, {
    dependency_id: t.string().primaryKey(),
    parent_component_id: t.string(),
    child_component_id: t.string(),
  }),

  // 5. Tenant leases tracking SLA penalty exposure per hour
  tenant_lease: table({ public: true }, {
    tenant_id: t.string().primaryKey(),
    name: t.string(),
    dependent_component_id: t.string(),
    hourly_sla_penalty: t.f64(),
  }),

  // 6. Time-series telemetry readings
  telemetry_reading: table({ public: true }, {
    reading_id: t.string().primaryKey(),
    component_id: t.string(),
    metric_name: t.string(), // e.g., "supply_temp", "chiller_load"
    value: t.f64(),
    timestamp: t.number(),
  }),

  // 7. Automated work orders generated by cascades
  work_order: table({ public: true }, {
    order_id: t.string().primaryKey(),
    component_id: t.string(),
    description: t.string(),
    status: t.string(), // "Pending", "Resolved"
    priority: t.string(), // "Urgent", "Normal"
  }),

  
  // ==========================================
  // MULTI-SILO ASSET CLASSIFICATION
  // ==========================================

  asset_profile: table({ public: true }, {
    component_id: t.string().primaryKey(),

    // HVAC, UTILITIES, ACCESS_CONTROL,
    // FACILITIES
    domain: t.string(),

    asset_name: t.string(),
    location: t.string(),

    // LOW, MEDIUM, HIGH, CRITICAL
    criticality: t.string(),
  }),

  // Operational event table

  
  // ==========================================
  // CROSS-SILO OPERATIONAL EVENTS
  // ==========================================

  operational_event: table({ public: true }, {
    event_id: t.string().primaryKey(),

    facility_id: t.string(),
    component_id: t.string(),

    // HVAC, UTILITIES, ACCESS_CONTROL,
    // FACILITIES
    domain: t.string(),

    // POWER_TRANSFER, READER_OFFLINE,
    // EQUIPMENT_FAULT, ACCESS_DELAY, etc.
    event_type: t.string(),

    // INFO, WARNING, CRITICAL
    severity: t.string(),

    description: t.string(),

    // SYNTHETIC, DATASET_REPLAY,
    // EXTERNAL_API
    source: t.string(),

    is_synthetic: t.bool(),

    // Unix milliseconds
    timestamp: t.number(),
  }), 

  
  // ==========================================
  // STEP 3: DEPENDENCY SEMANTICS
  // ==========================================

  dependency_rule: table({ public: true }, {
    dependency_id: t.string().primaryKey(),
    relationship_type: t.string(),
    requirement_group: t.string(),
  }),

  // Hypothetical cascade assessments.
  // No physical device state is changed.
  cascade_assessment: table({ public: true }, {
    assessment_id: t.string().primaryKey(),
    root_component_id: t.string(),
    predicted_at_risk_json: t.string(),
    predicted_at_risk_count: t.number(),
    affected_tenant_ids_json: t.string(),
    affected_tenant_count: t.number(),
    hourly_sla_exposure: t.number(),
    is_simulation: t.bool(),
    timestamp: t.number(),
  }),


  
  // ==========================================
  // STEP 4: ACTIVE FAULT TRACKING
  // ==========================================

  active_fault: table({ public: true }, {
    component_id: t.string().primaryKey(),
    incident_id: t.string(),
    work_order_id: t.string(),
    assessment_id: t.string(),
    status: t.string(),
    repeat_count: t.number(),
    first_detected_at: t.number(),
    last_detected_at: t.number(),
  }),


});

export default db;

